    Basic256Sha256_Sign = "Basic256Sha256_Sign"
    Basic256Sha256_SignAndEncrypt = "Basic256Sha256_SignAndEncrypt"
    Aes128Sha256RsaOaep_Sign = "Aes128Sha256RsaOaep_Sign"
