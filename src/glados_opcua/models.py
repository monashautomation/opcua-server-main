"""Validated configuration and address-space models.

All configuration is parsed into these Pydantic models before the listening
socket is opened.  Types deliberately mirror OPC UA concepts rather than Python
convenience: a bare integer in legacy YAML became an ``Int64`` on the wire, and
that distinction is preserved here by requiring an explicit ``data_type``.

The golden manifest in ``tests/fixtures/legacy_nodes.json`` is produced from
a running legacy server.  Config generated by ``scripts/migrate_legacy.py`` is
checked against it, so these models are the contract that tests enforce.
"""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum
from typing import Any
from urllib.parse import urlparse

from asyncua import ua
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


class StrictModel(BaseModel):
    """Reject unknown keys so configuration typos fail before startup."""

    model_config = ConfigDict(extra="forbid")


class Profile(StrEnum):
    """Deployment profile.

    ``LEGACY`` reproduces the original insecure-but-isolated behaviour: an
    optional NoSecurity endpoint, anonymous access and unrestricted node writes.
    ``PRODUCTION`` forbids anonymous access and NoSecurity and enforces the role
    matrix at the service boundary.  The profile is selected by
    ``GLADOS_PROFILE`` (higher precedence) or ``server.yaml``.
    """

    LEGACY = "legacy"
    PRODUCTION = "production"


class DataType(StrEnum):
    """OPC UA data types used by the legacy interface.

    Each member maps to an exact ``ua.VariantType`` and built-in DataType
    NodeId.  Keep this table explicit: inferring from Python values is how the
    legacy server ended up publishing ``R3d_BaseA`` and ``C1d_Img_h`` as Int64.
    """

    Boolean = "Boolean"
    SByte = "SByte"
    Byte = "Byte"
    Int16 = "Int16"
    UInt16 = "UInt16"
    Int32 = "Int32"
    UInt32 = "UInt32"
    Int64 = "Int64"
    UInt64 = "UInt64"
    Float = "Float"
    Double = "Double"
    String = "String"
    DateTime = "DateTime"
    ByteString = "ByteString"

    @property
    def variant_type(self) -> ua.VariantType:
        return _UA_TYPES[self][0]

    @property
    def data_type_id(self) -> int:
        return _UA_TYPES[self][1]

    def coerce(self, value: Any) -> Any:
        """Convert a YAML scalar to the exact Python value written on the wire."""
        if self is DataType.Boolean:
            return bool(value)
        if self in _INTEGER_TYPES:
            return int(value)
        if self in (DataType.Float, DataType.Double):
            return float(value)
        if self is DataType.String:
            return str(value)
        if self is DataType.ByteString:
            return bytes(value)
        if self is DataType.DateTime:
            return value if isinstance(value, datetime) else datetime.fromisoformat(str(value))
        return value


_UA_TYPES: dict[DataType, tuple[ua.VariantType, int]] = {
    DataType.Boolean: (ua.VariantType.Boolean, ua.ObjectIds.Boolean),
    DataType.SByte: (ua.VariantType.SByte, ua.ObjectIds.SByte),
    DataType.Byte: (ua.VariantType.Byte, ua.ObjectIds.Byte),
    DataType.Int16: (ua.VariantType.Int16, ua.ObjectIds.Int16),
    DataType.UInt16: (ua.VariantType.UInt16, ua.ObjectIds.UInt16),
    DataType.Int32: (ua.VariantType.Int32, ua.ObjectIds.Int32),
    DataType.UInt32: (ua.VariantType.UInt32, ua.ObjectIds.UInt32),
    DataType.Int64: (ua.VariantType.Int64, ua.ObjectIds.Int64),
    DataType.UInt64: (ua.VariantType.UInt64, ua.ObjectIds.UInt64),
    DataType.Float: (ua.VariantType.Float, ua.ObjectIds.Float),
    DataType.Double: (ua.VariantType.Double, ua.ObjectIds.Double),
    DataType.String: (ua.VariantType.String, ua.ObjectIds.String),
    DataType.DateTime: (ua.VariantType.DateTime, ua.ObjectIds.DateTime),
    DataType.ByteString: (ua.VariantType.ByteString, ua.ObjectIds.ByteString),
}

_INTEGER_TYPES = {
    DataType.SByte,
    DataType.Byte,
    DataType.Int16,
    DataType.UInt16,
    DataType.Int32,
    DataType.UInt32,
    DataType.Int64,
    DataType.UInt64,
}

_INT32_RANGE = (-(2**31), 2**31 - 1)
_INT64_RANGE = (-(2**63), 2**63 - 1)


class VariableCategory(StrEnum):
    """Semantic class used for documentation and the default write policy."""

    COMMAND = "command"
    TELEMETRY = "telemetry"
    FEEDBACK = "feedback"
    STATUS = "status"
    CONFIGURATION = "configuration"
    UNVERIFIED = "unverified"


class WriterRole(StrEnum):
    """Owner allowed to write a variable in production.

    ``ADMIN`` means the ownership has not been confirmed; such variables are
    intentionally writable only by administrators until migration review.
    """

    DEVICE = "device"
    CONTROLLER = "controller"
    ADMIN = "admin"


class UserRole(StrEnum):
    ADMIN = "admin"
    CONTROLLER = "controller"
    DEVICE = "device"
    MONITOR = "monitor"


