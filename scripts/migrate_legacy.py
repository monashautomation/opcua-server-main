"""Generate configuration from the archived legacy server.

Usage:
    python scripts/migrate_legacy.py \
        --source legacy/server_opcua.py \
        --baseline tests/fixtures/legacy_nodes.json \
        --output config

The source is parsed with :mod:`ast`; it is never imported or executed.  The
static extraction is compared with a runtime export from an isolated legacy
instance.  Any discrepancy is printed and the script exits non-zero *without*
writing configuration, preventing a silent interface change.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from glados_opcua.legacy_parser import (  # noqa: E402
    LegacyObject,
    baseline_objects,
    classify,
    differences,
    equipment_description,
    parse_legacy_source,
)

#: File prefixes preserve the legacy creation order when files are sorted.
GROUPS: list[tuple[str, list[str]]] = [
    ("01_communication", ["Communication", "Operator"]),
    ("02_magnetee", ["MagnetEE"]),
    ("03_robots", ["robot1", "robot2", "robot3", "robot4"]),
    ("04_printers", ["Printer1", "Printer2", "Printer3", "Printer4"]),
    ("05_camera", ["Camera1"]),
    ("06_robotdog", ["RobotDog1"]),
    ("07_air_purifiers", ["AirPurifier1", "AirPurifier2"]),
    ("08_gloves", ["Glove 1 (Left)", "Glove 2 (Right)"]),
    ("09_rgb_leds", ["500 RGB LEDs"]),
]

NAMESPACE_URIS: dict[int, str] = {
    0: "http://opcfoundation.org/UA/",
    1: "urn:freeopcua:python:server",
    2: "urn:glados:opcua:communication",
    3: "urn:glados:opcua:magnetee",
    **{index: f"urn:glados:opcua:printer{index - 10}" for index in range(11, 15)},
    **{index: f"urn:glados:opcua:robot{index - 20}" for index in range(21, 25)},
    29: "urn:glados:opcua:robotdog1",
    31: "urn:glados:opcua:camera1",
    41: "urn:glados:opcua:airpurifier1",
    42: "urn:glados:opcua:airpurifier2",
    51: "urn:glados:opcua:glove1",
    52: "urn:glados:opcua:glove2",
    53: "urn:glados:opcua:rgb-leds",
}

HEADER = """\
# Generated by scripts/migrate_legacy.py from {source}
# Baseline: {baseline}
# Do not hand-edit silently: every difference from the golden manifest is a
# compatibility review item. See docs/migration.md.
"""


def equipment_payload(obj: LegacyObject, baseline_path: Path) -> dict:
    match = baseline_objects(baseline_path)[(obj.namespace, obj.name)]
    variables = []
    for variable in obj.variables:
        category, writer, note = classify(variable.browse_name)
        item = {
            "browse_name": variable.browse_name,
            "node_id": variable.node_id,
            "browse_namespace": 0,
            "data_type": variable.data_type.value,
            "default": variable.default,
            "value_rank": -1,
            "writable": variable.writable,
            "category": category.value,
            "writer": writer.value,
        }
        if note:
            item["note"] = note
        variables.append(item)
    return {
        "name": obj.name,
        "namespace": obj.namespace,
        "node_id": match["node_id"],
        "browse_namespace": match["browse_name"]["namespace"],
        "description": equipment_description(obj.name),
        "variables": variables,
    }


def write_devices(objects: list[LegacyObject], baseline: Path, output: Path, source: Path) -> None:
    by_name = {obj.name: obj for obj in objects}
    used: set[str] = set()
    devices_dir = output / "devices"
    devices_dir.mkdir(parents=True, exist_ok=True)
    for filename, names in GROUPS:
        missing = [name for name in names if name not in by_name]
        if missing:
            raise SystemExit(f"legacy source is missing expected objects: {missing}")
        used.update(names)
        payload = {
            "config_version": 1,
            "equipment": [equipment_payload(by_name[name], baseline) for name in names],
        }
        path = devices_dir / f"{filename}.yaml"
        with path.open("w", encoding="utf-8") as handle:
            handle.write(HEADER.format(source=source, baseline=baseline))
            yaml.safe_dump(payload, handle, sort_keys=False, allow_unicode=True, width=110)
    leftovers = set(by_name) - used
    if leftovers:
        raise SystemExit(f"unclassified legacy objects: {sorted(leftovers)}")


def write_namespaces(objects: list[LegacyObject], output: Path, source: Path, baseline: Path) -> None:
    indexes = sorted({0, 1, *(obj.namespace for obj in objects)})
    entries = []
    for index in indexes:
        kind = "equipment" if index >= 2 else ("standard" if index == 0 else "application")
        entries.append(
            {
                "index": index,
                "uri": NAMESPACE_URIS[index],
                "kind": kind,
            }
        )
    # Operator lives in the application namespace; surface that in the file.
    for entry in entries:
        if entry["index"] == 1:
            entry["description"] = "Application namespace; hosts the legacy Operator object"
    payload = {"namespaces": entries}
    with (output / "namespaces.yaml").open("w", encoding="utf-8") as handle:
        handle.write(HEADER.format(source=source, baseline=baseline))
        handle.write(
            "# Unused indexes are filled with urn:glados:opcua:reserved:<index> at\n"
            "# startup so numeric indexes never shift.\n"
        )
        yaml.safe_dump(payload, handle, sort_keys=False, allow_unicode=True, width=110)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("legacy/server_opcua.py"))
    parser.add_argument("--baseline", type=Path, default=Path("tests/fixtures/legacy_nodes.json"))
    parser.add_argument("--output", type=Path, default=Path("config"))
    args = parser.parse_args()

    objects = parse_legacy_source(args.source)
    problems = differences(objects, args.baseline)
    if problems:
        print(f"{len(problems)} static/runtime discrepancies:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1

    write_devices(objects, args.baseline, args.output, args.source)
    write_namespaces(objects, args.output, args.source, args.baseline)
    count = sum(len(obj.variables) for obj in objects)
    writable = sum(1 for obj in objects for variable in obj.variables if variable.writable)
    print(
        json.dumps(
            {
                "objects": len(objects),
                "variables": count,
                "writable": writable,
                "static_matches_baseline": True,
                "output": str(args.output),
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
